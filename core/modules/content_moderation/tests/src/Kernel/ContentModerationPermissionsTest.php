declare(strict_types=1);

namespace Drupal\Tests\content_moderation\Kernel;

use Drupal\content_moderation\Permissions;
use Drupal\KernelTests\KernelTestBase;
use Drupal\workflows\Entity\Workflow;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;

/**
 * Test to ensure content moderation permissions are generated correctly.
 */
#[Group('content_moderation')]
#[RunTestsInSeparateProcesses]
class ContentModerationPermissionsTest extends KernelTestBase {

  /**
   * {@inheritdoc}
   */
  protected static $modules = [
    'workflows',
    'content_moderation',
    'workflow_type_test',
  ];

  /**
   * {@inheritdoc}
   */
  protected function setUp(): void {
    parent::setUp();
    $this->installEntitySchema('workflow');
  }

  /**
   * Tests permissions generated by content moderation.
   */
  #[DataProvider('permissionsTestCases')]
  public function testPermissions(array $workflow, array $permissions): void {
    Workflow::create($workflow)->save();
    $this->assertEquals($permissions, array_map(function (array $transitionPermission): array {
      $transitionPermission['title'] = (string) $transitionPermission['title'];
      $transitionPermission['description'] = (string) $transitionPermission['description'];
      return $transitionPermission;
    }, (new Permissions())->transitionPermissions()));
  }

