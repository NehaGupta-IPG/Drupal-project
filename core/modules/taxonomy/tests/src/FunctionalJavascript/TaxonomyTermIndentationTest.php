<?php

declare(strict_types=1);

namespace Drupal\Tests\taxonomy\FunctionalJavascript;

use Behat\Mink\Element\NodeElement;
use Drupal\FunctionalJavascriptTests\WebDriverTestBase;
use Drupal\Tests\taxonomy\Traits\TaxonomyTestTrait;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;

/**
 * Ensure that the term indentation works properly.
 */
#[Group('taxonomy')]
#[RunTestsInSeparateProcesses]
class TaxonomyTermIndentationTest extends WebDriverTestBase {

  use TaxonomyTestTrait;

  /**
   * {@inheritdoc}
   */
  protected static $modules = ['taxonomy'];

  /**
   * {@inheritdoc}
   */
  protected $defaultTheme = 'stark';

  /**
   * Xpath selector for the indentation markup rendered in a term row.
   *
   * @var string
   */
  protected static $indentationXpathSelector = "child::td[1]/*[contains(concat(' ', normalize-space(@class), ' '), ' js-indentation ')][contains(concat(' ', normalize-space(@class), ' '), ' indentation ')]";

  /**
   * Vocabulary for testing.
   *
   * @var \Drupal\taxonomy\VocabularyInterface
   */
  protected $vocabulary;

  /**
   * {@inheritdoc}
   */
  protected function setUp(): void {
    parent::setUp();
    $this->drupalLogin($this->drupalCreateUser([
      'administer taxonomy',
    ]));
    $this->vocabulary = $this->createVocabulary();
  }

  /**
   * Tests term indentation using the tabledrag JavaScript behavior.
   */
  public function testTermIndentation(): void {
    $assert = $this->assertSession();

    // Create three taxonomy terms. Weights are set explicitly so the terms
    // are guaranteed to be listed in this order on the overview page,
    // regardless of the random term names generated by createTerm().
    $term1 = $this->createTerm($this->vocabulary, ['weight' => 0]);
    $term2 = $this->createTerm($this->vocabulary, ['weight' => 1]);
    $this->createTerm($this->vocabulary, ['weight' => 2]);

    // Get the taxonomy storage.
    $taxonomy_storage = $this->container->get('entity_type.manager')->getStorage('taxonomy_term');

    $this->drupalGet('admin/structure/taxonomy/manage/' . $this->vocabulary->id() . '/overview');
    $assert->waitForElementVisible('css', 'a.tabledrag-handle');

    // No terms have been indented yet.
    $assert->elementsCount('xpath', static::$indentationXpathSelector, 0, $this->findTermRow($term1->id()));
    $assert->elementsCount('xpath', static::$indentationXpathSelector, 0, $this->findTermRow($term2->id()));

    // Use the tabledrag keyboard interaction (the accessible equivalent of
    // dragging the row with a mouse) to indent term 2 underneath term 1.
    $this->moveRowWithKeyboard($term2->id(), 'right', 1);

    // The row should now be rendered with one level of indentation, and the
    // hidden depth/parent fields updated by the JavaScript accordingly.
    $term2_row = $this->findTermRow($term2->id());
    $this->assertSame('1', $term2_row->find('css', 'input.term-depth')->getValue());
    $this->assertSame((string) $term1->id(), $term2_row->find('css', 'input.term-parent')->getValue());
    $assert->pageTextContains('You have unsaved changes.');

    // Save the form and check for the HTML indentation element presence.
    $this->getSession()->getPage()->pressButton('Save');
    $assert->waitForElementVisible('css', 'a.tabledrag-handle');
    $assert->elementExists('xpath', "//table[@id='taxonomy']/tbody/tr/" . static::$indentationXpathSelector);

    // Check explicitly that term 2's parent is term 1.
    $taxonomy_storage->resetCache();
    $parents = $taxonomy_storage->loadParents($term2->id());
    $this->assertEquals($term1->id(), key($parents), 'Term 1 is the term 2\'s parent');

    // Move the second term back out to the root level.
    $this->moveRowWithKeyboard($term2->id(), 'left', 0);

    $term2_row = $this->findTermRow($term2->id());
    $this->assertSame('0', $term2_row->find('css', 'input.term-depth')->getValue());

    $this->getSession()->getPage()->pressButton('Save');
    $assert->waitForElementVisible('css', 'a.tabledrag-handle');
    // All terms back at the root level, no indentation should be present.
    $assert->elementNotExists('xpath', "//table[@id='taxonomy']/tbody/tr/" . static::$indentationXpathSelector);

    // Check explicitly that term 2 has no parents.
    $taxonomy_storage->resetCache();
    $parents = $taxonomy_storage->loadParents($term2->id());
    $this->assertEmpty($parents, 'Term 2 has no parents now');
  }

  /**
   * Finds the term row in the overview table for the given term ID.
   *
   * @param string|int $tid
   *   The term ID.
   *
   * @return \Behat\Mink\Element\NodeElement
   *   The row element.
   */
  protected function findTermRow(string|int $tid): NodeElement {
    $xpath = "//table[@id='taxonomy']/tbody/tr[.//input[contains(concat(' ', normalize-space(@class), ' '), ' term-id ') and @value='$tid']]";
    $row = $this->getSession()->getPage()->find('xpath', $xpath);
    $this->assertNotEmpty($row, "Row for term $tid not found.");
    return $row;
  }

  /**
   * Moves a term's row through the keyboard-accessible tabledrag behavior.
   *
   * @param string|int $tid
   *   The term ID whose row should be moved.
   * @param string $arrow
   *   The arrow key to press. Either 'left' (decrease indentation) or
   *   'right' (increase indentation, nesting under the previous row).
   * @param int $expected_indentation
   *   The indentation level the row is expected to reach once the
   *   JavaScript has processed the key press.
   */
  protected function moveRowWithKeyboard(string|int $tid, string $arrow, int $expected_indentation): void {
    $keys = [
      'left' => 37,
      'right' => 39,
    ];
    $this->assertArrayHasKey($arrow, $keys, 'The arrow parameter must be one of "left" or "right".');

    $handle = $this->findTermRow($tid)->find('css', 'a.tabledrag-handle');
    $handle->focus();
    $handle->keyDown($keys[$arrow]);
    $handle->keyUp($keys[$arrow]);
    $handle->blur();

    // Key events are dispatched asynchronously with respect to the
    // WebDriver command that triggers them, so wait until tabledrag.js has
    // actually updated the row's indentation markup.
    $row = $this->findTermRow($tid);
    $reached_expected_indentation = $row->waitFor(5, fn () => count($row->findAll('xpath', static::$indentationXpathSelector)) === $expected_indentation);
    $this->assertTrue($reached_expected_indentation, "Row for term $tid did not reach indentation level $expected_indentation in time.");
  }

}
