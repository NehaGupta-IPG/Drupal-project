<?php

declare(strict_types=1);

namespace Drupal\Tests\sqlite\Kernel\sqlite;

use Drupal\KernelTests\Core\Database\AutoGeneratedIndexTestTrait;
use Drupal\KernelTests\Core\Database\DriverSpecificSchemaTestBase;
use Drupal\sqlite\Driver\Database\sqlite\Schema;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;

/**
 * Tests schema API for the SQLite driver.
 */
#[Group('Database')]
#[RunTestsInSeparateProcesses]
#[CoversClass(Schema::class)]
class SchemaTest extends DriverSpecificSchemaTestBase {

  use AutoGeneratedIndexTestTrait;

  /**
   * {@inheritdoc}
   */
  public function checkSchemaComment(string|false $description, string $table, ?string $column = NULL): void {
    // The sqlite driver schema does not support fetching table/column
    // comments.
  }

  /**
   * {@inheritdoc}
   */
  protected function tryInsertExpectsIntegrityConstraintViolationException(string $tableName): void {
    // Sqlite does not throw an IntegrityConstraintViolationException here.
  }

  /**
   * {@inheritdoc}
   */
  public function testTableWithSpecificDataType(): void {
    $table_specification = [
      'description' => 'Schema table description.',
      'fields' => [
        'timestamp'  => [
          'sqlite_type' => 'datetime',
          'not null' => FALSE,
          'default' => NULL,
        ],
      ],
    ];
    $this->schema->createTable('test_timestamp', $table_specification);
    $this->assertTrue($this->schema->tableExists('test_timestamp'));
  }

  /**
   * Tests introspect index schema.
   *
   * @legacy-covers \Drupal\sqlite\Driver\Database\sqlite\Schema::introspectIndexSchema
   */
  public function testIntrospectIndexSchema(): void {
    $table_specification = [
      'fields' => [
        'id'  => [
          'type' => 'int',
          'not null' => TRUE,
          'default' => 0,
        ],
        'test_field_1'  => [
          'type' => 'int',
          'not null' => TRUE,
          'default' => 0,
        ],
        'test_field_2'  => [
          'type' => 'int',
          'default' => 0,
        ],
        'test_field_3'  => [
          'type' => 'int',
          'default' => 0,
        ],
        'test_field_4'  => [
          'type' => 'int',
          'default' => 0,
        ],
        'test_field_5'  => [
          'type' => 'int',
          'default' => 0,
        ],
      ],
      'primary key' => ['id', 'test_field_1'],
      'unique keys' => [
        'test_field_2' => ['test_field_2'],
        'test_field_3_test_field_4' => ['test_field_3', 'test_field_4'],
      ],
      'indexes' => [
        'test_field_4' => ['test_field_4'],
        'test_field_4_test_field_5' => ['test_field_4', 'test_field_5'],
      ],
    ];

    $table_name = strtolower($this->getRandomGenerator()->name());
    $this->schema->createTable($table_name, $table_specification);

    unset($table_specification['fields']);

    $introspect_index_schema = new \ReflectionMethod(get_class($this->schema), 'introspectIndexSchema');
    $index_schema = $introspect_index_schema->invoke($this->schema, $table_name);

    $this->assertEquals($table_specification, $index_schema);
  }

  /**
   * Tests JSON schema type.
   *
   * @see https://www.sqlite.org/json1.html#jptr
   */
  public function testJsonSchema(): void {
    $this->doTestJsonSchema();
    foreach (self::JSON_TEST_DATA as $path => $expected) {
      $query = $this->connection->select('test_json');
      // JSON_EXTRACT() in SQLite has some unique behavior, which is abstracted
      // in the driver's Condition class. The syntax here ensures we're only
      // testing our basic integration with the schema API; the abstraction is
      // tested elsewhere.
      $query->addExpression('json_extract([test_field], :path, "$._")', NULL, [
        ':path' => $path,
      ]);
      $actual = json_decode($query->execute()->fetchField(), TRUE)[0];
      $this->assertSame($expected, $actual);
    }
  }

  /**
   * Tests automatic optimization to use a JSON expression index.
   *
   * @covers ::indexExists
   */
  public function testJsonOptimization(): void {
    $this->schema->createTable('test_json', static::jsonTableSpecification());
    $query = $this->connection->select('test_json');
    $query->jsonCondition('test_field', '$.number', 0);
    $query->addExpression('id');
    $explained = $this->connection->query(
      'EXPLAIN QUERY PLAN ' . $query,
      $query->getArguments(),
      // This would normally get pulled through automatically, however since we
      // are doing EXPLAIN here, we need to re-set it explicitly for _this_
      // query.
      ['strict_params' => $query->usesStrictParameters()]
    )->fetchAssoc();
    $this->assertStringContainsString('USING INDEX', $explained['detail'], 'Expression index not used in query.');
    $introspect_index_schema = new \ReflectionMethod(get_class($this->schema), 'introspectIndexSchema');
    $index_schema = $introspect_index_schema->invoke($this->schema, 'test_json');
    // Expression indexes are stored as strings in the indexes array.
    $expression_indexes = array_filter($index_schema['indexes'], 'is_string');
    $this->assertNotEmpty($expression_indexes, 'Expression indexes should be present.');
    $this->assertTrue($this->schema->indexExists('test_json', array_key_first($expression_indexes)));
  }

  /**
   * Tests cleanup of expression indexes when a JSON field is dropped.
   */
  public function testExpressionIndexCleanup(): void {
    $this->schema->createTable('test_json', static::jsonTableSpecification());
    $introspect = new \ReflectionMethod(get_class($this->schema), 'introspectIndexSchema');
    $index_schema = $introspect->invoke($this->schema, 'test_json');
    $expression_indexes = array_filter($index_schema['indexes'], 'is_string');
    $this->assertCount(3, $expression_indexes);
    $this->schema->dropField('test_json', 'test_field');
    $index_schema_after = $introspect->invoke($this->schema, 'test_json');
    $this->assertEmpty(array_filter($index_schema_after['indexes'] ?? [], 'is_string'));
  }

}
