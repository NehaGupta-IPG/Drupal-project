#[Group('Mail')]
class SymfonyMailerTest extends UnitTestCase {

  use EmailTestDataTrait;

  /**
   * Tests that mixed plain text and html body is converted correctly.
   */
  public function testFormatResemblesHtml(): void {
    // Populate global $base_path to avoid notices generated by
    // MailFormatHelper::htmlToMailUrls()
    global $base_path;
    $original_base_path = $base_path;
    $base_path = '/';

    $variables = [
      '@form-url' => 'https://www.example.com/contact',
      '@sender-url' => 'https://www.example.com/user/123',
      // The sender name is put into HTML markup and must not contain HTML
      // special characters: MailFormatHelper::htmlToText() would strip or
      // decode them, while the expected value below uses the raw string.
      '@sender-name' => $this->randomMachineName(),
    ];

    $plain = "In HTML, ampersand must be written as &amp;.\nI saw your house and <wow> it is great. There is too much to say about that beautiful building, it will never fit on one line of text.\nIf a<b and b<c then a<c.";
    $template = "@sender-name (@sender-url) sent a message using the contact form at @form-url.";
    $markup = Markup::create(strtr($template, $variables));

    $message = [
      'body' => [
        $plain,
        $markup,
      ],
    ];

    /** @var \Symfony\Component\Mailer\MailerInterface|\PHPUnit\Framework\MockObject\MockObject */
    $mailer = $this->createStub(MailerInterface::class);

    /** @var \Psr\Log\LoggerInterface|\PHPUnit\Framework\MockObject\MockObject */
    $logger = $this->createStub(LoggerInterface::class);

    $plugin = new SymfonyMailer($logger, $mailer);
    $message = $plugin->format($message);

    $expect = MailFormatHelper::wrapMail($plain . "\n\n" . strtr($template, $variables) . "\n");
    $this->assertEquals($expect, $message['body']);

    $base_path = $original_base_path;
  }

  /**
   * Tests sending a mail with special characters in various fields.
   *
   * @param array $message
   *   An array containing the following keys for an email message:
   *     - from
   *     - reply-to
   *     - to
   *     - subject.
   * @param array $expected
   *   An array containing the following keys from the email headers from the
   *   sent email:
   *     - from
   *     - reply-to
   *     - to
   *     - subject.
   *
   * @legacy-covers ::mail
   */
  #[DataProvider('providerMail')]
  public function testMail(array $message, array $expected): void {
    // Setup a mail message.
    $message += [
      'id' => 'example_key',
      'module' => 'example',
      'key' => 'key',
      'langcode' => 'en',
      'params' => [],
      'send' => TRUE,
      'body' => '',
      'headers' => [
        'MIME-Version' => '1.0',
        'Content-Type' => 'text/plain; charset=utf-8; format=flowed; delsp=yes',
        'Content-Transfer-Encoding' => '8Bit',
        'X-Mailer' => 'Drupal',
        'From' => '"Foo, Bar, and Baz" <from@example.org>',
        'Reply-to' => 'from@example.org',
        'Return-Path' => 'from@example.org',
      ],
    ];

    /** @var \Symfony\Component\Mailer\MailerInterface|\PHPUnit\Framework\MockObject\MockObject */
    $mailer = $this->getMockBuilder(MailerInterface::class)->getMock();
    $mailer->expects($this->once())->method('send')
      ->with(
        $this->logicalAnd(
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->get('mime-version')->getBodyAsString() === '1.0'
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->has('content-type') === FALSE
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->has('content-transfer-encoding') === FALSE
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->get('x-mailer')->getBodyAsString() === 'Drupal'
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->get('from')->getBodyAsString() === $expected['from']
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->get('reply-to')->getBodyAsString() === $expected['reply-to']
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->get('to')->getBodyAsString() === $expected['to']
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getHeaders()->get('subject')->getBodyAsString() === $expected['subject']
          ),
          $this->callback(fn (Email $email): bool =>
            $email->getTextBody() === ''
          )
        )
      );

    /** @var \Psr\Log\LoggerInterface|\PHPUnit\Framework\MockObject\MockObject */
    $logger = $this->createStub(LoggerInterface::class);

    $plugin = new SymfonyMailer($logger, $mailer);
    $this->assertTrue($plugin->mail($message));
  }

  /**
   * Data provider for testMail().
   */
  public static function providerMail(): array {
    // Verify we use line endings consistent with the PHP mail() function, which
    // changed with PHP 8. See:
    // - https://www.drupal.org/node/3270647
    // - https://bugs.php.net/bug.php?id=81158
    $line_end = "\r\n";

    return [
      'defaults' => [
        [
          'from' => 'from@example.org',
          'reply-to' => 'from@example.org',
          'to' => 'to@example.org',
          'subject' => 'test subject',
        ],
        [
          'from' => '"Foo, Bar, and Baz" <from@example.org>',
          'reply-to' => 'from@example.org',
          'to' => 'to@example.org',
          'subject' => 'test subject',
        ],
      ],
      'line endings in subject' => [
        [
          'from' => 'from@example.org',
          'reply-to' => 'from@example.org',
          'to' => 'to@example.org',
          'subject' => "test\r\nsubject",
        ],
        [
          'from' => '"Foo, Bar, and Baz" <from@example.org>',
          'reply-to' => 'from@example.org',
          'to' => 'to@example.org',
          'subject' => "=?utf-8?Q?test?=$line_end =?utf-8?Q?subject?=",
        ],
      ],
      'multiple comma-separated recipients' => [
        [
          'from' => 'from@example.org',
          'reply-to' => 'from@example.org',
          'to' => 'foo@example.org,bar@example.org',
          'subject' => 'test subject',
        ],
        [
          'from' => '"Foo, Bar, and Baz" <from@example.org>',
          'reply-to' => 'from@example.org',
          'to' => 'foo@example.org, bar@example.org',
          'subject' => 'test subject',
        ],
      ],
    ];
  }

  /**
   * Tests historical UASG addresses through the mail backend and envelope.
   */
  #[DataProvider('uasgEnvelopeProvider')]
  public function testUasgRecipient(string $mailbox, bool $valid, string $encoded): void {
    $captured = [];
    $mailer = $this->createMock(MailerInterface::class);
    $mailer->expects($valid ? $this->once() : $this->never())->method('send')->willReturnCallback(
      static function (Email $email) use (&$captured): void {
        foreach (Envelope::create($email)->getRecipients() as $recipient) {
          $captured[] = $recipient->getEncodedAddress();
        }
      }
    );
    $logger = $this->createStub(LoggerInterface::class);
    $plugin = new SymfonyMailer($logger, $mailer);
    $this->assertSame($valid, $plugin->mail([
      'to' => $mailbox,
      'headers' => ['From' => 'sender@example.org'],
      'subject' => 'Internationalized recipient test',
      'body' => 'No real transport is used.',
    ]));
    $this->assertSame($valid ? [$encoded] : [], $captured);
  }

  /**
   * Tests separator mapping and exact local-part preservation in the envelope.
   */
  #[DataProvider('normalizedDomainMailboxProvider')]
  public function testNormalizedDomainRecipient(string $mailbox, string $normalized): void {
    $captured = [];
    $mailer = $this->createMock(MailerInterface::class);
    $mailer->expects($this->once())->method('send')->willReturnCallback(
      static function (Email $email) use (&$captured): void {
        foreach (Envelope::create($email)->getRecipients() as $recipient) {
          $captured[] = $recipient->getEncodedAddress();
        }
      }
    );
    $plugin = new SymfonyMailer($this->createStub(LoggerInterface::class), $mailer);
    $this->assertTrue($plugin->mail([
      'to' => $mailbox,
      'headers' => ['From' => 'sender@example.org'],
      'subject' => 'Domain separator test',
      'body' => 'No real transport is used.',
    ]));
    // This fixture domain has a fixed IDNA form. Do not normalize the local part.
    // cspell:ignore fsqu
    $encoded = str_replace('@例子.测试', '@xn--fsqu00a.xn--0zwm56d', $normalized);
    $this->assertSame([$encoded], $captured);
  }

  /**
   * Tests accepted and rejected local-part lengths before transport delivery.
   */
  #[DataProvider('recipientLengthProvider')]
  public function testRecipientLength(string $mailbox, bool $valid, string $header): void {
    $mailer = $this->createMock(MailerInterface::class);
    $mailer->expects($valid ? $this->once() : $this->never())->method('send');
    $plugin = new SymfonyMailer($this->createStub(LoggerInterface::class), $mailer);
    $headers = ['From' => 'sender@example.org'];
    if ($header !== 'To') {
      $headers[$header] = $mailbox;
    }
    $this->assertSame($valid, $plugin->mail([
      'to' => $header === 'To' ? $mailbox : 'recipient@example.org',
      'headers' => $headers,
      'subject' => 'Mailbox length test',
      'body' => 'No real transport is used.',
    ]));
  }

  /**
   * Provides octet boundaries, including copied and blind copied recipients.
   */
  public static function recipientLengthProvider(): array {
    return [
      '64 ASCII octets' => [str_repeat('a', 64) . '@example.org', TRUE, 'To'],
      '65 ASCII octets' => [str_repeat('a', 65) . '@example.org', FALSE, 'To'],
      '64 UTF-8 octets' => [str_repeat('é', 32) . '@example.org', TRUE, 'To'],
      '66 UTF-8 octets' => [str_repeat('é', 33) . '@example.org', FALSE, 'To'],
      'Overlong Cc' => [str_repeat('a', 65) . '@example.org', FALSE, 'Cc'],
      'Overlong Bcc' => [str_repeat('é', 33) . '@example.org', FALSE, 'Bcc'],
    ];
  }

}
