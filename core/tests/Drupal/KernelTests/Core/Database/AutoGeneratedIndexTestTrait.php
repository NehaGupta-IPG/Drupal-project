<?php

declare(strict_types=1);

namespace Drupal\KernelTests\Core\Database;

/**
 * Test trait for database drivers which automatically create indexes for JSON.
 */
trait AutoGeneratedIndexTestTrait {

  /**
   * Tests that adding fields to existing tables also generates their indexes.
   */
  public function testAddFieldWithAutoGeneratedIndexes(): void {
    $spec = static::JSON_TABLE_SPECIFICATION;
    $field = $spec['fields']['test_field'];
    unset($spec['fields']['test_field']);
    $this->schema->createTable('test_json', $spec);
    $this->schema->addField(
      'test_json',
      'test_field',
      $field
    );
    $introspect_index_schema = new \ReflectionMethod(get_class($this->schema), 'introspectIndexSchema');
    $indexes = $introspect_index_schema->invoke($this->schema, 'test_json')['indexes'];
    $this->assertCount(3, $indexes);
    foreach (array_keys($indexes) as $index) {
      $this->assertStringContainsString('auto_gen_test_field_', $index);
    }
  }

}
