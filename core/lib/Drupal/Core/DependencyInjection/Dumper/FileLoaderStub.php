<?php

declare(strict_types=1);

namespace Drupal\Core\DependencyInjection\Dumper;

/**
 * Stub for Symfony's FileLoader when symfony/config is not installed.
 *
 * Symfony's PhpDumper references FileLoader::ANONYMOUS_ID_REGEXP to filter
 * anonymous service IDs. The real FileLoader class requires symfony/config
 * which is not a Drupal runtime dependency. This stub provides just the
 * constant so PhpDumper can function without it.
 *
 * @internal
 *
 * @todo Remove this class when Symfony moves this constant to
 *   ContainerBuilder.
 *
 * @see \Symfony\Component\DependencyInjection\Dumper\PhpDumper
 * @see https://github.com/symfony/symfony/issues/64005
 */
abstract class FileLoaderStub {

  /**
   * Regexp matching anonymous service IDs generated by Symfony's loaders.
   */
  public const ANONYMOUS_ID_REGEXP = '/^\.\d+_[^~]*+~[._a-zA-Z\d]{7}$/';

}
