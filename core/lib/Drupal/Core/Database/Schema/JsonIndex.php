<?php

declare(strict_types=1);

namespace Drupal\Core\Database\Schema;

use Drupal\Core\Database\Query\JsonCastType;

/**
 * Represents a JSON expression index in a schema definition.
 *
 * Use as an element in the 'indexes' array of a table schema to declare an
 * expression index on a specific JSON path. Can be combined with regular
 * column names to create composite indexes. Each database driver converts
 * this into the appropriate driver-specific index DDL.
 *
 * @code
 * $schema = [
 *   'fields' => [
 *     'data' => ['type' => 'json'],
 *     'status' => ['type' => 'int', 'not null' => TRUE],
 *   ],
 *   'indexes' => [
 *     // JSON-only index.
 *     'idx_score' => [JsonIndex::on('data', '$.score', JsonCastType::Int)],
 *     // Composite index mixing a regular column and a JSON expression.
 *     'idx_status_cat' => ['status', JsonIndex::on('data', '$.category')],
 *   ],
 * ];
 * @endcode
 *
 * The expression SQL used for the index is generated by each driver's
 * JsonExpression class, ensuring byte-for-byte parity with query expressions.
 */
final class JsonIndex {

  /**
   * Constructs a JsonIndex object.
   *
   * @param string $field
   *   The JSON column name.
   * @param string $jsonpath
   *   The JSONPath expression (e.g. '$.status').
   * @param \Drupal\Core\Database\Query\JsonCastType $type
   *   The cast type for the index expression.
   */
  public function __construct(
    public readonly string $field,
    public readonly string $jsonpath,
    public readonly JsonCastType $type = JsonCastType::Text,
  ) {}

  /**
   * Creates a JsonIndex instance.
   *
   * @param string $field
   *   The JSON column name.
   * @param string $jsonpath
   *   The JSONPath expression (e.g. '$.status').
   * @param \Drupal\Core\Database\Query\JsonCastType $type
   *   The cast type.
   *
   * @return self
   *   A new JsonIndex instance.
   */
  public static function on(string $field, string $jsonpath, JsonCastType $type = JsonCastType::Text): self {
    return new self($field, $jsonpath, $type);
  }

}
