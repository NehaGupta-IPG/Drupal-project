use Drupal\Core\Mailer\EmailPluginInterface;
use Symfony\Component\Mime\Email;

/**
 * @defgroup mailer Experimental Mailer
 * @{
 * Define content, behavior and appearance of transactional email.
 *
 * @section sec_overview Overview and terminology
 *
 * There are two activities when it comes to send transactional mail from
 * Drupal:
 *
 * - Building mails
 * - Delivering mails
 *
 * The experimental mailer delegates mail delivery to the Symfony Mailer
 * component and provides a convenient toolkit based on well known Drupal
 * patterns for the mail building activity.
 *
 * The following sections of this topic provide an overview of the mailer API.
 * For more detailed information, see
 * https://www.drupal.org/developing/api/8/mailer
 *
 * @section sec_register Registering emails as YAML plugin
 * To register an email, add lines similar to this to a module_name.emails.yml
 * file in your top-level module directory:
 * @code
 * user.password_reset:
 *   label: 'Password recovery'
 *   html_body_template: 'user_email_html_body'
 * @endcode
 * Some notes:
 * - The first line is the machine name of the email. Typically, it is prefixed
 *   by the machine name of the module that defines the email.
 * - The 'label' property contains the human-readable name of the email.
 * - The 'html_body_template' property specifies which twig template to use
 *   when rendering an email.
 *
 * Email definitions registered by other modules can be altered using
 * hook_email_info_alter().
 *
 * @todo Derivatives will probably be defined for these; when they are, add
 *   documentation here.
 *
 * @section sec_plugin Registering emails using PHP attributes
 * For some emails a simple twig template is not enough. For more complex cases,
 * a plugin class can be used to override existing behavior and prepare data
 * for use in an email message.
 *
 * The following steps are necessary to define an email in a module:
 * - Create a new class that implements the
 *   \Drupal\Core\Mailer\EmailPluginInterface, in the namespace Plugin\Email
 *   under a module namespace. For more information about creating plugins,
 *   see the @link plugin_api Plugin API topic. @endlink
 * - Usually this class should extend the \Drupal\Core\Mailer\EmailPluginDefault
 *   class, which provides the basics for setting headers and building various
 *   email message parts.
 *
 * This is an example of a basic email plugin class:
 * @code
 * namespace Drupal\my_module\Plugin\Email;
 *
 * use Drupal\Core\Mailer\Attribute\Email;
 * use Drupal\Core\Mailer\EmailPluginDefault;
 * #[Email(
 *   id: "my_module.my_message",
 *   label: new TranslatableMarkup("My Message"),
 * )]
 * class MyMessage extends EmailPluginDefault {
 *
 *   public function htmlBody(): RenderableInterface|array|null {
 *     $build['colors'] = [
 *       '#markup' => '<p><em>All</em> <strong>colors</strong> <u>are</u> <span class="rainbow">beautiful</span></p>',
 *     ];
 *     return $build;
 *   }
 *
 * }
 * @endcode
 *
 * Some plugins will need to display some information stored in the Drupal
 * database, which will involve using one or more Drupal services (see the
 * @link container Services and container topic @endlink). In order to properly
 * inject services, a plugin should implement
 * \Drupal\Core\Plugin\ContainerFactoryPluginInterface.
 * @}
 */

