/**
 * Alter all the email definitions discovered by the email plugin manager.
 *
 * @param array<string,mixed[]> &$definitions
 *   The discovered email definitions to be altered. Each definition has a key
 *   that is the machine name, which must be unique.
 *
 *   The value corresponding to each machine name key is an array representing
 *   the email definition from an emails.yml file or an #[Email(...)] attribute.
 *
 * @ingroup mailer
 */
function hook_email_info_alter(array &$definitions): void {
}

/**
 * Alter the email plugin instance before the email message is built.
 *
 * @param \Drupal\Core\Mailer\EmailPluginInterface $email
 *   The email plugin instance representing the message which is about to be
 *   built.
 *
 * @ingroup mailer
 */
function hook_email_pre_build_alter(EmailPluginInterface $email): void {
}

/**
 * Alter the email data array generated by the email plugin.
 *
 * @param array $email_data
 *   An associative array representing an email message about to be rendered:
 *   - body: An associative array with the following keys and values:
 *     - html: A render array (or NULL) representing the HTML part of a message.
 *     - text: A \Stringable or a render array (or NULL) representing the text
 *       part of a message.
 *   - headers: An associative array of key-value pairs where the key is a
 *     header name and the value is its content.
 *   - symfony_email_class: A subclass of \Symfony\Component\Mime\Email used as
 *     when handing over the email message to the delivery layer.
 * @param array $context
 *   An associative array containing the following:
 *   - email: The email plugin instance.
 *
 * @ingroup mailer
 */
function hook_email_pre_render_alter(array &$email_data, array $context): void {
}

/**
 * Alter the rendered Symfony email object.
 *
 * @param \Symfony\Component\Mime\Email $symfony_email
 *   The Symfony email object.
 * @param array $context
 *   An associative array containing the following:
 *   - email: The email plugin instance.
 *   - body: An associative array with the following keys and values:
 *     - html: A render array (or NULL) representing the HTML part of a message.
 *     - text: A \Stringable or a render array (or NULL) representing the text
 *       part of a message.
 *   - assets: An instance of Drupal\Core\Asset\AttachedAssetsInterface which
 *     contains settings and assets collected while rendering the email body.
 *
 * @ingroup mailer
 */
function hook_email_post_render_alter(Email $symfony_email, array $context): void {
}

